"""Fetch selected items: re-verify criteria, download 1024px thumb, strip metadata, record provenance.
Usage: python3 -I fetch.py selection.tsv OUT_META.json MEDIA_DIR DOWNLOAD_TMP_DIR
"""
import sys, os, io, json, csv, urllib.request, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import commons
from PIL import Image

sel_path, out_path, media_dir, tmp_dir = sys.argv[1:5]
os.makedirs(tmp_dir, exist_ok=True)
meta = json.load(open(out_path)) if os.path.exists(out_path) else {}
AI_HINTS = ("AI-generated", "generated by", "by DALL-E", "by Midjourney", "by Stable Diffusion", "by Flux",
            "Adobe Firefly", "thispersondoesnotexist", "GPT Image", "by ChatGPT", "by Gemini", "Generative adversarial")
QI_HINTS = ("Quality images", "Featured pictures", "Valued images")
for row in csv.DictReader(open(sel_path), delimiter="\t"):
    slug = row["slug"]
    if slug in meta and os.path.exists(os.path.join(media_dir, slug + ".jpg")):
        continue
    info = commons.info([row["title"]])[0]
    hidden = commons.api({"action": "query", "titles": row["title"], "prop": "categories", "clshow": "hidden", "cllimit": "500"})
    hcats = [c["title"] for c in hidden["query"]["pages"][0].get("categories", [])]
    cats = info["allcats"]
    problems = []
    if row["label"] == "real":
        if not info["ts"] or info["ts"] >= "2021-01-01": problems.append("uploaded too late")
        if not (info["make"] and info["model"]): problems.append("no camera EXIF")
        quality = [c for c in cats + hcats if any(h in c for h in QI_HINTS)]
    else:
        aicats = [c for c in cats if any(h.lower() in c.lower() for h in AI_HINTS)]
        if not aicats: problems.append("no AI category")
        quality = []
    req = urllib.request.Request(info["thumb"], headers={"User-Agent": commons.UA})
    raw = urllib.request.urlopen(req, timeout=120).read(); time.sleep(1)
    with open(os.path.join(tmp_dir, slug + ".orig"), "wb") as fh: fh.write(raw)
    im = Image.open(io.BytesIO(raw))
    im = im.convert("RGB")
    if im.width > 1024:
        im = im.resize((1024, round(im.height * 1024 / im.width)), Image.LANCZOS)
    clean = Image.new("RGB", im.size); clean.paste(im)  # fresh image object: no info/exif/icc carried over
    dest = os.path.join(media_dir, slug + ".jpg")
    clean.save(dest, "JPEG", quality=85, optimize=True)
    meta[slug] = dict(row, page=info["page"], ts=info["ts"], user=info["user"], license=info["license"],
                      licenseUrl=info["licenseUrl"], artist=info["artist"], credit=info["credit"],
                      make=info["make"], model=info["model"], dto=info["dto"], desc=info["desc"],
                      cats=cats, qualitycats=quality, width=clean.width, height=clean.height,
                      origw=info["w"], origh=info["h"], problems=problems)
    print(slug, clean.size, info["license"], "|", info["make"], info["model"], "|", problems or "ok", "|", quality[:2])
    json.dump(meta, open(out_path, "w"), ensure_ascii=False, indent=1)
